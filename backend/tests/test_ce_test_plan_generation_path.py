@pytest.mark.asyncio
async def test_malformed_non_truncated_bridge_output_runs_tool_recovery_protocol():
    """CE must pass raw malformed output to the generator's repair pipeline."""
    from app.tools.test_plan_generator_tool import TestPlanGeneratorTool

    class _Resolver:
        def evaluate(self, key):
            return key in {"CONTEXT_ENGINE_AGENT_ENABLED", "MIG_GENERATE"}

    class _Bridge:
        available = True

        def __init__(self):
            self.calls = []

        async def generate(self, **kwargs):
            self.calls.append(kwargs)
            mode = kwargs["task_state_ref"].get("generation_mode")
            if mode == "json_syntax_recovery_outline":
                return SimpleNamespace(value=(
                    '{"terminology":{},"cross_cutting":[],'
                    'chapter_summaries":{"overview":"summary",'
                    '"scope":"summary","strategy":"summary"}}'
                ))
            if mode == "json_syntax_recovery_batch":
                fields = kwargs["task_state_ref"]["batch_fields"]
                if fields == ["overview", "scope"]:
                    return SimpleNamespace(value=(
                        '{"overview":"Payment release overview",'
                        '"scope":[[{"module":"payment"}]]}'
                    ))
                return SimpleNamespace(value='{"strategy":"Risk-based testing"}')
            # Validly closed but syntactically invalid: this is not truncation.
            return SimpleNamespace(value='{"overview":"bad",}')

    bridge = _Bridge()
    ctx = SimpleNamespace(
        task_id="task_malformed_json",
        task_internal_id=61,
        conversation_internal_id=62,
        user_internal_id=63,
        task_flag_resolver=_Resolver(),
        context_llm_invoker=bridge,
        knowledge_search_result={},
        requirement_analysis={"text_content": "payment requirement"},
        template_structure={
            "sections": [
                {"title": "Overview", "children": []},
                {"title": "Scope", "children": []},
                {"title": "Strategy", "children": []},
            ],
            "generation_config": {
                "ai_fields": [
                    {"field": "overview", "title": "Overview", "section_id": "overview"},
                    {
                        "field": "scope",
                        "title": "Scope",
                        "section_id": "scope",
                        "table_schemas": [{"headers": ["module"]}],
                    },
                    {"field": "strategy", "title": "Strategy", "section_id": "strategy"},
                ],
                "keep_sections": [],
                "manual_sections": [],
                "section_bindings": [],
            },
        },
        test_plan_content=None,
    )

    result = await TestPlanGeneratorTool().run({}, ctx)

    assert result["success"] is True
    recovery = result["data"]["generation_recovery"]
    assert recovery["kind"] == "json_syntax_outline_batch"
    assert recovery["repair_attempted"] is True
    assert recovery["json_error_position"] == {"line": 1, "column": 18}
    assert recovery["recovery_round"] == 2
    assert recovery["status"] == "recovered"
    assert recovery["completed_batches"] == 2
    assert recovery["successful_field_count"] == 3
    assert bridge.calls[0]["llm_task_profile"].name == "test_plan_generation_raw"
    assert bridge.calls[1]["task_state_ref"]["generation_mode"] == "json_syntax_repair"
    assert bridge.calls[1]["llm_task_profile"].name == "test_plan_generation_json_repair_raw"
    assert bridge.calls[2]["task_state_ref"]["generation_mode"] == "json_syntax_recovery_outline"
    assert bridge.calls[3]["task_state_ref"]["batch_fields"] == ["overview", "scope"]
    assert bridge.calls[4]["task_state_ref"]["batch_fields"] == ["strategy"]


