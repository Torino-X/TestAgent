    assert '"overview"' in bridge.kwargs["output_contract"]
    assert "ALLOWED JSON FIELDS" in bridge.kwargs["system_prompt"]
    assert "overview: Overview" in bridge.kwargs["system_prompt"]
    assert "never wrap it in table, content, title, value, or data" in bridge.kwargs["system_prompt"]
