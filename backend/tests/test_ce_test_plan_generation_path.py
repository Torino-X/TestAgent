@pytest.mark.asyncio
async def test_long_requirement_extracts_every_chunk_before_final_generation(monkeypatch):
    from app.context_engine.evidence.requirement_pipeline import RequirementEvidencePreparer
    import app.tools.test_plan_generator_tool as generator_module
    from app.tools.test_plan_generator_tool import TestPlanGeneratorTool

    original_preparer = RequirementEvidencePreparer
    monkeypatch.setattr(
        generator_module,
        "RequirementEvidencePreparer",
        lambda: original_preparer(
            direct_limit_tokens=80,
            chunk_limit_tokens=48,
            estimate=len,
        ),
    )

    class _Resolver:
        def evaluate(self, key):
            return key in {"CONTEXT_ENGINE_AGENT_ENABLED", "MIG_GENERATE"}

    class _Bridge:
        available = True

        def __init__(self):
            self.calls = []

        async def generate(self, **kwargs):
            self.calls.append(kwargs)
            if kwargs["call_site"] == "test_plan.requirement.extract":
                chunk_id = kwargs["task_state_ref"]["chunk_id"]
                return SimpleNamespace(value=f"{chunk_id} extracted requirement ledger")
            return SimpleNamespace(value='{"overview": "generated from complete ledger"}')

    bridge = _Bridge()
    requirement_text = "\n\n".join(
        f"REQ-{index:03d} exact requirement detail {index}"
        for index in range(16)
    )
    ctx = SimpleNamespace(
        task_id="task_long",
        task_internal_id=11,
        conversation_internal_id=12,
        user_internal_id=13,
        task_flag_resolver=_Resolver(),
        context_llm_invoker=bridge,
        knowledge_search_result={},
        requirement_analysis={
            "source_ref": "file_long_requirement",
            "document_name": "long-requirements.md",
            "text_content": requirement_text,
        },
        template_structure={
            "sections": [{"title": "1 Overview", "children": []}],
            "generation_config": {
                "ai_fields": [
                    {
                        "field": "overview",
                        "title": "Overview",
                        "section_id": "sec_1",
                        "level": 1,
                    }
                ],
                "keep_sections": [],
                "manual_sections": [],
                "section_bindings": [],
            },
        },
        test_plan_content=None,
    )

    result = await TestPlanGeneratorTool().run({}, ctx)

    assert result["success"] is True
    extraction_calls = [
        call for call in bridge.calls
        if call["call_site"] == "test_plan.requirement.extract"
    ]
    final_call = bridge.calls[-1]
    assert len(extraction_calls) > 1
    assert final_call["call_site"] == "test_plan.generate.outline"
    evidence = final_call["task_state_ref"]["context_evidence"]
    assert evidence["coverage_manifest"]["coverage_complete"] is True
    assert evidence["coverage_manifest"]["source_characters"] == len(requirement_text)
    assert len(evidence["parsed_documents"]) == len(extraction_calls)
    assert final_call["task_state_ref"]["conversation_policy"] == {
        "recent_complete_turns": 6,
        "include_summary": False,
        "protect_recent_turns": True,
    }
    assert "REQ-000" in extraction_calls[0]["current_goal"]
    assert "REQ-015" in extraction_calls[-1]["current_goal"]


